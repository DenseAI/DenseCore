#!/usr/bin/env python3
"""Regenerate the Unicode 15 category masks used by the o200k pre-tokenizer."""
import pathlib
import unicodedata

if unicodedata.unidata_version != "15.0.0":
    raise SystemExit("Regeneration requires Python with Unicode 15.0.0")


def mask(cp):
    category = unicodedata.category(chr(cp))
    return (int(category in ("Lu", "Lt", "Lm", "Lo") or category.startswith("M")) |
            (int(category in ("Ll", "Lm", "Lo") or category.startswith("M")) << 1) |
            (int(category.startswith("L")) << 2) | (int(category.startswith("N")) << 3))


ranges = []
start = 0
previous = mask(0)
for cp in range(1, 0x110001):
    current = mask(cp) if cp < 0x110000 else -1
    if current != previous:
        if previous:
            ranges.append((start, cp - 1, previous))
        start, previous = cp, current
out = pathlib.Path(__file__).resolve().parents[1] / "src/models/o200k_categories.inl"
out.write_text("// Generated by core/scripts/generate_o200k_categories.py; Unicode 15.0.0.\n"
               "// upper/uncased/mark=1, lower/uncased/mark=2, letter=4, number=8.\n"
               "constexpr struct { uint32_t first, last; uint8_t mask; } kO200kCategories[] = {\n" +
               "".join(f"    {{0x{a:X}, 0x{b:X}, {m}}},\n" for a, b, m in ranges) + "};\n")
